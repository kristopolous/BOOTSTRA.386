#!/bin/bash
#
# BOOTSTRA/386 v3: compile the Less and lay out dist/ without the 2014
# toolchain. Needs node (uses npx for less and clean-css) and python3.
#
#   ./build-386.sh          # dist/ and the copies the docs use
#
set -e
cd "$(dirname "$0")"
root=..

lessc() { npx --yes -p less@4 lessc "$@"; }
cleancss() { npx --yes -p clean-css-cli@5 cleancss "$@"; }

mkdir -p dist/css/fonts dist/js
lessc less/bootstrap.less dist/css/bootstrap.css
lessc less/theme.less dist/css/bootstrap-theme.css
cleancss -o dist/css/bootstrap.min.css dist/css/bootstrap.css
cleancss -o dist/css/bootstrap-theme.min.css dist/css/bootstrap-theme.css

# The js is the plugins in the Gruntfile's order, 386.js first
js="386 transition alert button carousel collapse dropdown modal tooltip popover scrollspy tab affix"
{
  cat <<'HDR'
/*!
 * BOOTSTRA/386 v3.3.2, Bootstrap v3.3.2 (http://getbootstrap.com)
 * Copyright 2011-2015 Twitter, Inc.
 * Licensed under MIT (https://github.com/twbs/bootstrap/blob/master/LICENSE)
 */

if (typeof jQuery === 'undefined') {
  throw new Error('Bootstrap\'s JavaScript requires jQuery')
}

HDR
  for f in $js; do cat "js/$f.js"; echo; done
} > dist/js/bootstrap.js
npx --yes -p terser@5 terser --compress --mangle --comments "/^!/" -o dist/js/bootstrap.min.js dist/js/bootstrap.js
{
  echo "// This file is autogenerated via the \`commonjs\` Grunt task. You can require() this file in a CommonJS environment."
  for f in $js; do echo "require('../../js/$f.js')"; done
} > dist/js/npm.js

# The font lives next to the css, where scaffolding.less points
for ext in otf svg woff; do cp -p "$root/fonts/Fixedsys500c.$ext" dist/css/fonts/; done
for ext in eot ttf; do [[ -e "_gh_pages/assets/css/fonts/Fixedsys500c.$ext" ]] && cp -p "_gh_pages/assets/css/fonts/Fixedsys500c.$ext" dist/css/fonts/; done

# The docs link ../dist/css and ../dist/js
for d in docs/dist _gh_pages/dist; do
  [[ -L "$d" || "$d/css" -ef dist/css ]] && continue   # docs/dist points at dist/
  mkdir -p "$d/css" "$d/js" "$d/fonts"
  cp -p dist/css/*.css "$d/css/"
  cp -pr dist/css/fonts "$d/css/"
  [[ -d dist/fonts ]] && cp -p dist/fonts/* "$d/fonts/" 2>/dev/null || true
  [[ -d dist/js ]] && cp -p dist/js/*.js "$d/js/" 2>/dev/null || true
done
ls -la dist/css/bootstrap.css dist/css/bootstrap.min.css
